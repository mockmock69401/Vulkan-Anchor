package net.vulkanmod.visuals.vk.shader;

import org.junit.jupiter.api.Test;
import org.lwjgl.system.MemoryUtil;
import org.lwjgl.util.shaderc.Shaderc;

import java.nio.ByteBuffer;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.*;

/**
 * P7i: SMAA's shaders are third_party/smaa/smaa-*.comp with smaa.h spliced in, preprocessed by shaderc (GlslForVulkan
 * does not evaluate #if). The results are checked in; this test fails when they no longer match their sources.
 * Regenerate with -Dvulkanmod.visuals.regenSmaa=true (gradlew test --tests '*SmaaShadersTest' -Dvulkanmod.visuals.regenSmaa=true).
 */
class SmaaShadersTest {
    static final String[] PASSES = {"edges", "weights", "blend"};
    private static final Path SOURCES = Path.of("third_party/smaa"), OUTPUT = Path.of("src/main/resources/assets/vulkanmod/visuals/shaders/post");

    /** The notice the preprocessed shaders carry: the preprocessor drops smaa.h's comments, its licence must stay. */
    static String notice() throws Exception {
        String iryoku = Files.readString(SOURCES.resolve("LICENSE-smaa.txt"), StandardCharsets.ISO_8859_1);
        String turol = Files.readString(SOURCES.resolve("LICENSE-smaaDemo.txt"), StandardCharsets.ISO_8859_1);
        return "/*\n * Generated by SmaaShadersTest from third_party/smaa (do not edit): SMAA by Jorge Jimenez et al.\n"
                + " * (iryoku/smaa) through turol/smaaDemo's compute shaders, both under the MIT licence:\n *\n"
                + (iryoku.strip() + "\n\n" + turol.strip()).lines().map(l -> (" * " + l).stripTrailing()).collect(Collectors.joining("\n"))
                + "\n */\n";
    }

    static String generate(String pass) throws Exception {
        String wrapper = Files.readString(SOURCES.resolve("smaa-" + pass + ".comp"), StandardCharsets.UTF_8);
        String header = Files.readString(SOURCES.resolve("smaa.h"), StandardCharsets.ISO_8859_1);
        String source = wrapper.replace("#include \"smaa.h\"", header);
        long compiler = Shaderc.shaderc_compiler_initialize();
        long options = Shaderc.shaderc_compile_options_initialize();
        //The source is too large for LWJGL's stack encoding: it goes in a malloc'd buffer
        ByteBuffer src = MemoryUtil.memUTF8(source, false), name = MemoryUtil.memUTF8("smaa_" + pass), entry = MemoryUtil.memUTF8("main");
        long result;
        try {
            result = Shaderc.shaderc_compile_into_preprocessed_text(compiler, src, Shaderc.shaderc_glsl_compute_shader, name, entry, options);
        } finally {
            MemoryUtil.memFree(src);
            MemoryUtil.memFree(name);
            MemoryUtil.memFree(entry);
        }
        try {
            assertNotEquals(0L, result);
            assertEquals(Shaderc.shaderc_compilation_status_success, Shaderc.shaderc_result_get_compilation_status(result),
                    Shaderc.shaderc_result_get_error_message(result));
            byte[] bytes = new byte[(int) Shaderc.shaderc_result_get_length(result)];
            Shaderc.shaderc_result_get_bytes(result).get(bytes);
            String text = new String(bytes, StandardCharsets.UTF_8);
            String body = text.lines().filter(l -> !l.startsWith("#line") && !l.isBlank()).collect(Collectors.joining("\n")) + "\n";
            int versionEnd = body.indexOf('\n') + 1;
            assertTrue(body.startsWith("#version 450"), body.substring(0, Math.min(80, body.length())));
            return body.substring(0, versionEnd) + notice() + body.substring(versionEnd);
        } finally {
            if (result != 0L) Shaderc.shaderc_result_release(result);
            Shaderc.shaderc_compile_options_release(options);
            Shaderc.shaderc_compiler_release(compiler);
        }
    }

    @Test
    void theCheckedInShadersMatchTheirSources() throws Exception {
        boolean regen = Boolean.getBoolean("vulkanmod.visuals.regenSmaa");
        for (String pass : PASSES) {
            String generated = generate(pass);
            Path out = OUTPUT.resolve("smaa_" + pass + ".comp");
            if (regen) {
                Files.writeString(out, generated, StandardCharsets.UTF_8);
            } else {
                assertTrue(Files.exists(out), out + " missing: run with -Dvulkanmod.visuals.regenSmaa=true");
                assertEquals(generated, Files.readString(out, StandardCharsets.UTF_8), out + " is stale: run with -Dvulkanmod.visuals.regenSmaa=true");
            }
            assertFalse(generated.contains("#if"), "no conditionals left for GlslForVulkan");
            assertTrue(generated.contains("Jorge Jimenez") && generated.contains("Turo Lamminen"), "the licence notice");
            if (!pass.equals("blend")) {
                //SMAA stores only where it finds something: every pixel is cleared first (stale edges would smear)
                String main = generated.substring(generated.lastIndexOf("void main()"));
                assertTrue(main.indexOf("imageStore(outputImage, coord, vec4(0.0))") >= 0, pass);
            }
        }
    }
}
